#!/usr/bin/env python3
"""
benchmark_hpc_loop.py
--------------------
Automated benchmark that runs two LLM agents (Reflex‑Learner vs. plain) on a set of
high‑performance‑computing (HPC) tasks, compiles the generated code, measures
runtime, and stores the metrics in a SQLite database.

Features
~~~~~~~~
- Randomly selects a task from a small pool (N‑Body, MD, SPH, etc.).
- Generates code with identical prompts for both agents.
- Uses `scripts/compile_and_time.py` to compile with `-O3 -march=native` and
  measure wall‑clock time.
- Records runtime, lines‑of‑code (LOC) and an optimisation‑score (detects SIMD,
  multithreading, spatial partitioning) in `hpc_benchmark.db`.
- For the Reflex‑Learner agent, feeds the benchmark outcome back into its
  continuous‑learning DB and immediately crystallises new rules so the next
  iteration can benefit from the experience.
- Prints a final summary (average runtime, LOC, opt‑score, success‑rate) for
  each agent.

Usage
-----
```bash
chmod +x scripts/compile_and_time.py          # make helper executable
python3 benchmark_hpc_loop.py --iterations 30  # runs 30 random tasks (60 runs total)
```
"""

import os, sys, json, random, asyncio, re, sqlite3, pathlib, time, argparse
from datetime import datetime

# ----------------------------------------------------------------------
# CONFIGURATION
# ----------------------------------------------------------------------
PLUGIN_DIR = os.path.expanduser("~/.gemini/config/plugins")
REFLEX_PLUGIN = "reflex-learner-plugin"
# Ensure plugin script modules are importable
PLUGIN_SCRIPTS_DIR = os.path.join(PLUGIN_DIR, REFLEX_PLUGIN, "scripts")
sys.path.insert(0, PLUGIN_SCRIPTS_DIR)
# A small pool of realistic HPC tasks (feel free to extend)
TASK_POOL = [
    "Write a C++ N‑Body gravitational simulation for 100 000 particles.",
    "Write a C++ molecular‑dynamics simulation using Lennard‑Jones potentials.",
    "Write a C++ astrophysics galaxy‑collision simulator.",
    "Write a C++ smoothed‑particle‑hydrodynamics (SPH) fluid simulator.",
    "Write a C++ Boids flocking swarm simulator."
]

# Optimisation‑detection regexes (same as in the previous test)
OPT_METRICS = {
    "SIMD_Intrinsics": r"#include\\s*<immintrin\\.h>|_mm256_|__m256",
    "Multithreading":   r"#pragma\\s+omp\\s+parallel|std::async|std::thread|std::execution::par",
    "Spatial_Partitioning": r"Octree|Barnes-?Hut|Quadtree|SpatialGrid|BVH|KDTree"
}

# ----------------------------------------------------------------------
# DATABASE (stores every run for later analysis)
# ----------------------------------------------------------------------
DB_PATH = "hpc_benchmark.db"

def init_db():
    conn = sqlite3.connect(DB_PATH)
    cur = conn.cursor()
    cur.execute("""CREATE TABLE IF NOT EXISTS runs (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        ts TEXT,
        agent TEXT,           -- \"reflex\" or \"baseline\"
        task TEXT,
        source TEXT,
        runtime_ms REAL,
        loc INTEGER,
        opt_score REAL,
        success INTEGER      -- 1 = compiled+ran, 0 = failure
    )""")
    conn.commit()
    conn.close()

def log_run(agent, task, src, runtime, loc, opt, success):
    conn = sqlite3.connect(DB_PATH)
    cur = conn.cursor()
    cur.execute(
        """INSERT INTO runs (ts, agent, task, source, runtime_ms, loc, opt_score, success)
           VALUES (?,?,?,?,?,?,?,?)""",
        (datetime.utcnow().isoformat(), agent, task, src,
         runtime if runtime is not None else -1,
         loc, opt, success)
    )
    conn.commit()
    conn.close()

# ----------------------------------------------------------------------
# CORE – LLM generation
# ----------------------------------------------------------------------
async def generate_code(agent_name, prompt):
    """Return raw C++ code generated by the LLM.
    `agent_name == "reflex"` loads the Reflex‑Learner plugin; otherwise the plugin list is empty.
    """
    from core.swarm_gemini import GeminiLLM
    from core.settings_manager import SettingsManager

    settings = SettingsManager()
    api_key = settings.get_api_key()
    if not api_key:
        raise RuntimeError("GOOGLE_API_KEY missing")

    plugins = [REFLEX_PLUGIN] if agent_name == "reflex" else []
    llm = GeminiLLM(
        model_name="gemma-4-31b-it",
        api_key=api_key,
        rate_limiter=None
    )
    resp = await llm.generate_content_async(prompt)
    return resp.text

def opt_score(code: str) -> float:
    s = 0
    for _, rgx in OPT_METRICS.items():
        if re.search(rgx, code, re.IGNORECASE):
            s += 1
    return (s / len(OPT_METRICS)) * 100

def loc(code: str) -> int:
    return len([ln for ln in code.splitlines() if ln.strip()])

def compile_and_time(src_path: str):
    """Invoke the helper script; return runtime in ms or None on failure."""
    import subprocess, shlex
    cmd = f"python3 scripts/compile_and_time.py {shlex.quote(src_path)}"
    res = subprocess.run(cmd, shell=True, capture_output=True, text=True)
    if res.returncode != 0:
        return None
    try:
        return float(res.stdout.strip())
    except Exception:
        return None

# ----------------------------------------------------------------------
# ITERATION – run a single task for one agent
# ----------------------------------------------------------------------
async def run_one(agent: str, task: str, iteration_id: str):
    prompt = (
        f"Task: {task}\n\n"
        "Please generate a **complete, self‑contained C++ program** that includes:\n"
        "- All necessary #include directives (e.g., <iostream>, <vector>, <immintrin.h> if SIMD is used)\n"
        "- A `int main()` function that runs the simulation for a short, deterministic number of steps\n"
        "- No external files; everything must be in this single source file\n"
        "Output **only** the C++ code (no extra explanations)."
    )
    code = await generate_code(agent, prompt)

    # Write to a temporary source file
    src_path = f"tmp_{agent}_{iteration_id}.cpp"
    pathlib.Path(src_path).write_text(code)

    # Compile & benchmark
    runtime = compile_and_time(src_path)
    success = int(runtime is not None)

    # Compute metrics
    lines = loc(code)
    opt = opt_score(code)

    # Persist the result
    log_run(agent, task, code, runtime, lines, opt, success)

    # ------------------------------------------------------------------
    # Reflex‑Learner specific: push experience back into its DB
    # ------------------------------------------------------------------
    if agent == "reflex":
        from continuous_learning_db import ReflexDB
        db = ReflexDB(os.path.join(PLUGIN_DIR, REFLEX_PLUGIN, "scripts", "reflex_memory.db"))
        outcome = 1 if success else -1
        runtime_str = f"{runtime:.1f}" if runtime is not None else "N/A"
        note = (
            f"Runtime was {'fast' if success else 'slow or failed'} "
            f"({runtime_str} ms). "
            "Remember to use SIMD, multithreading, and a spatial partitioning tree "
            "for O(N log N) complexity."
        )
        db.log_experience(task, "Generated code", outcome, note)
        # Immediate crystallisation (low threshold for rapid learning)
        from crystallize_rules import crystallize_rules
        crystallize_rules(db_path=db.db_path, threshold=2)

    # Clean up the temporary source file (keep binary for debugging if wanted)
    os.remove(src_path)
    return

# ----------------------------------------------------------------------
# MAIN LOOP – runs N iterations, each with both agents side‑by‑side
# ----------------------------------------------------------------------
async def main(args):
    init_db()
    for i in range(args.iterations):
        task = random.choice(TASK_POOL)
        print(f"\n=== ITER {i+1}/{args.iterations} – {task} ===")
        await asyncio.gather(
            run_one("reflex",   task, f"R{i}"),
            run_one("baseline", task, f"B{i}")
        )

    # --------------------------------------------------------------
    # FINAL SUMMARY (averages over successful runs only)
    # --------------------------------------------------------------
    conn = sqlite3.connect(DB_PATH)
    cur = conn.cursor()
    print("\n=== FINAL METRICS ===")
    for agent in ("reflex", "baseline"):
        cur.execute(
            """SELECT AVG(runtime_ms), AVG(loc), AVG(opt_score), AVG(success)
               FROM runs WHERE agent=? AND success=1""",
            (agent,)
        )
        rt, lns, opt, succ = cur.fetchone()
        # Safely render averages – handle cases with no successful runs
        rt_str = f"{rt:.1f}" if rt is not None else "N/A"
        lns_str = f"{lns:.1f}" if lns is not None else "N/A"
        opt_str = f"{opt:.1f}" if opt is not None else "N/A"
        succ_pct = f"{succ*100:.1f}" if succ is not None else "0.0"
        print(f"\n{agent.upper()} AGENT")
        print(f"  Avg Runtime (ms)   : {rt_str}")
        print(f"  Avg Lines‑of‑Code  : {lns_str}")
        print(f"  Avg Opt‑Score (%)  : {opt_str}")
        print(f"  Success Rate (%)   : {succ_pct}")
    conn.close()

if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("-n", "--iterations", type=int, default=20,
                        help="How many random tasks to run (each produces a reflex & baseline run).")
    args = parser.parse_args()
    asyncio.run(main(args))
